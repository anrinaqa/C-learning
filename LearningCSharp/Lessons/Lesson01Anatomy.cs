// СЛОЙ 1: using — подключение чужого кода (библиотек).
// Похоже на import в других языках. Если видишь
// "using OpenQA.Selenium;" — файл работает с Selenium.
using System.Text;

// СЛОЙ 2: namespace — "папка" для кода. Логическая группировка.
// Обычно повторяет структуру папок проекта.
namespace LearningCSharp.Lessons;

// СЛОЙ 3: class — контейнер для кода. Почти весь код в C#
// живёт внутри классов. "public" = виден из других файлов.
public static class Lesson01Anatomy
{
    // СЛОЙ 4: метод — блок кода внутри класса, который что-то делает.
    // Разбор подписи метода слева направо:
    //   public  — кто может вызвать (public = все)
    //   static  — можно вызвать без создания объекта (про это в уроке 4)
    //   void    — что метод возвращает (void = ничего)
    //   Run     — имя метода
    //   ()      — параметры (пусто = без параметров)
    public static void Run()
    {
        // Тело метода — между фигурными скобками { }.
        // Каждая команда заканчивается точкой с запятой ;
        // Нет ; — код не компилируется. Частая ошибка новичков.

        Console.WriteLine("Привет! Это урок 1.");

        // Вложенность — главный навык чтения кода.
        // Скобки всегда идут парами: { открыл — } закрыл.
        // Чтобы понять, где заканчивается блок — смотри на отступы
        // или кликай на скобку в IDE (она подсветит парную).
        if (true)
        {
            var sb = new StringBuilder();
            sb.Append("Этот код внутри блока if.");
            sb.Append(" У него свои фигурные скобки.");
            Console.WriteLine(sb.ToString());
        }

        // КОММЕНТАРИИ:
        //   // — однострочный (всё после // до конца строки — текст)
        //   /* ... */ — многострочный
        //   /// — документация к методу/классу (XML-doc)
        // Комментарии не выполняются — это пояснения для людей.
        // ИИ-агент оставляет их часто — читай, там бывает полезное.
    }
}

