// Переменная — именованная коробка для данных.
// В C# у каждой переменной есть ТИП — что в ней лежит.
// ============================================================

namespace LearningCSharp.Lessons;

public static class Lesson02Variables
{
    public static void Run()
    {
        // Читаем объявление переменной слева направо:
        //   тип  имя   = значение;
        //    |    |        |
        //   int  count  = 5;

        // Основные типы, которые ты увидишь везде:
        int number = 42;                    // целое число
        double price = 19.99;               // дробное число
        bool isLoggedIn = true;             // true или false
        string userName = "test_user";      // текст (в кавычках!)
        char letter = 'A';                  // один символ (одинарные кавычки)

        Console.WriteLine($"number={number}, price={price}, logged={isLoggedIn}, letter={letter}");

        // var — "выведи тип сам". Компилятор подставит тип за тебя.
        // var timeout = 30;  — это int, потому что 30 — целое.
        // ВАЖНО: var не значит "любой тип". Тип фиксируется раз и навсегда.
        var timeout = 30;
        // timeout = "тридцать";  // ОШИБКА компиляции: нельзя строку в int

        // Строки и интерполяция — подстановка значений в текст.
        // $ перед кавычкой = внутри { } можно вставлять переменные.
        string greeting = $"Пользователь {userName}, таймаут {timeout} сек";
        Console.WriteLine(greeting);

        // Конкатенация — склейка строк через + (старый способ):
        Console.WriteLine("Тестовые данные: " + number + ", " + price);

        // null — отдельный тип значения: "ничего нет".
        // Самая частая причина падений в тестах!
        string? emptyValue = null;  // ? после типа = "может быть null"
        Console.WriteLine(emptyValue?.Length ?? -1); // подробнее про ?. и ?? — урок 9

        // Типизированные ошибки — что ищет компилятор:
        // int x = "пять";       // не скомпилируется
        // bool flag = "true";   // не скомпилируется (строка != bool)
        // bool flag2 = true;    // ок
    }
}

// ============================================================
// ЧТО ЗАПОМНИТЬ:
//  - Тип стоит слева от имени: string name, int count
//  - var — не "без типа", а "тип понятен из контекста"
//  - "текст" — string, 'символ' — char, true/false — bool
//  - null = отсутствие значения, источник 80% багов
// ============================================================
